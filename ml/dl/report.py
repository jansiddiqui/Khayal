"""ml/results/dl_decline.md, dl_decline.csv and dl_sweep.csv, plus figures: confusion matrices, detection delay,
false alarms vs delay (threshold sweep), training curves."""

import csv
from collections.abc import Sequence
from pathlib import Path

import numpy as np

from ml.decline.simulator import PROFILES
from ml.dl.data import FLAG_ABILITY_DROP, flag_onset_day
from ml.dl.metrics import CONSECUTIVE_DAYS, THRESHOLD, Scores, mean_std, score
from ml.dl import report_extra as X
from ml.dl.run import METHOD_TITLES, METHODS, SeedResult, checkpoint_days
from ml.dl.train import TrainConfig

SERIES, RULE, INK, MUTED, GRID = "#2a78d6", "#8a8984", "#1f1e1c", "#52514e", "#e5e4df"
SHORT = {"rule_b": "Rule B", "mlp": "MLP", "gru": "GRU", "lstm": "LSTM", "gru_no_study": "GRU\nno study"}


def _fmt(ms: tuple[float, float] | None, digits: int = 3) -> str:
    return "—" if ms is None else f"{ms[0]:.{digits}f} ± {ms[1]:.{digits}f}"


def per_seed_scores(results: Sequence[SeedResult]) -> dict[str, list[Scores]]:
    return {m: [score(r.outcomes[m]) for r in results] for m in METHODS}


def to_rows(results: Sequence[SeedResult]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []

    def add(method: str, seed: int | str, metric: str, group: str, value: float | None) -> None:
        rows.append({"method": method, "seed": seed, "metric": metric, "group": group,
                     "value": "" if value is None else round(float(value), 6)})

    for r in results:
        for m in METHODS:
            s = score(r.outcomes[m])
            add(m, r.seed, "accuracy", "all", s.accuracy)
            add(m, r.seed, "macro_f1", "all", s.macro_f1)
            for p in PROFILES:
                add(m, r.seed, "recall", p, s.recall[p])
            add(m, r.seed, "false_alarm_rate", "healthy", s.false_alarm_rate)
            add(m, r.seed, "false_alarm_day_median", "healthy", s.false_alarm_day_median)
            for d, outs in r.checkpoints[m].items():
                cs = score(outs)
                add(m, r.seed, "accuracy_by_day", f"day_{d}", cs.accuracy)
                add(m, r.seed, "macro_f1_by_day", f"day_{d}", cs.macro_f1)
            for p in ("mci", "moderate"):
                add(m, r.seed, "detected", p, s.detected[p])
                add(m, r.seed, "delay_median_days", p, s.delay_median[p])
            for i, p in enumerate(PROFILES):
                for j, col in enumerate((*PROFILES, "undecided")):
                    add(m, r.seed, f"confusion_{col}", p, s.confusion[i, j])
        for m, h in r.histories.items():
            add(m, r.seed, "best_epoch", "all", h.best_epoch + 1)
            add(m, r.seed, "best_val_loss", "all", min(h.val_loss))
    return rows


def to_markdown(results: Sequence[SeedResult], per_profile: int, days: int, cfg: TrainConfig) -> str:
    scores = per_seed_scores(results)
    n = results[0].n_patients
    seeds = len(results)

    def ms(method: str, get) -> tuple[float, float] | None:  # type: ignore[no-untyped-def]
        return mean_std([get(s) for s in scores[method]])

    onset = {p: flag_onset_day(p) for p in ("mci", "moderate")}
    lines = [
        "# Deep learning vs the rule for decline detection",
        "",
        f"Generated by `python -m ml.dl.run --per-profile {per_profile} --days {days} --seeds {seeds}`.",
        "",
        f"Each seed simulates a new cohort of {per_profile} patients per profile ({3 * per_profile} in all, {days} days, "
        f"`ml.decline.simulator`), split by patient into {n['train']} train / {n['val']} validation / {n['test']} "
        "test. Every method is scored on the same test patients. Values are mean ± standard deviation over "
        f"{seeds} seeds (seed = cohort, split and model initialisation).",
        "",
        "## Profile on the last day",
        "",
        "Rule B's profile is the overall cognitive index status on the last day (Stable → healthy, Watch → mci, "
        "Declining → moderate; Learning counts as wrong). The models' profile is the profile head's most likely "
        "class after the last session.",
        "",
        "| Method | Accuracy | Macro F1 | Recall healthy | Recall mci | Recall moderate |",
        "|---|---|---|---|---|---|",
    ]
    for m in METHODS:
        lines.append(
            f"| {METHOD_TITLES[m]} | {_fmt(ms(m, lambda s: s.accuracy))} | {_fmt(ms(m, lambda s: s.macro_f1))} | "
            + " | ".join(_fmt(ms(m, lambda s, p=p: s.recall[p])) for p in PROFILES)
            + " |"
        )
    lines += [
        "",
        "## Early warning at threshold 0.5",
        "",
        f"A model flags a patient on the day its P(decline) has been ≥ {THRESHOLD} for {CONSECUTIVE_DAYS} days in a "
        "row (the day an alert could fire; days without play keep the last value). Rule B flags on the day of its "
        "first decline alert. Decline starts on day 0, so that day is the detection delay. False alarm = a healthy "
        "patient flagged at any time. Delay = median over flagged patients, then mean ± std over seeds.",
        "",
        "| Method | False alarm rate (healthy) | False alarm day | MCI detected | MCI delay, days "
        "| Moderate detected | Moderate delay, days |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in METHODS:
        lines.append(
            f"| {METHOD_TITLES[m]} | {_fmt(ms(m, lambda s: s.false_alarm_rate))} | "
            f"{_fmt(ms(m, lambda s: s.false_alarm_day_median), 1)} | "
            f"{_fmt(ms(m, lambda s: s.detected['mci']))} | {_fmt(ms(m, lambda s: s.delay_median['mci']), 1)} | "
            f"{_fmt(ms(m, lambda s: s.detected['moderate']))} | {_fmt(ms(m, lambda s: s.delay_median['moderate']), 1)} |"
        )
    lines += [
        "",
        "The models' delays depend on the early-warning target they were trained on (see Method: it switches on at "
        f"day {onset['mci']} for mci and day {onset['moderate']} for moderate), so they are not a pure measure of how early the data shows "
        "decline. The next table compares the methods without that target.",
        "",
        "## How early each method tells the profile",
        "",
        "Profile accuracy using only the sessions up to the given day (the rule: index status that evening; the "
        "models: their profile head after that day's play). No early-warning target is involved.",
        "",
        "| Method | " + " | ".join(f"Day {d}" for d in (*checkpoint_days(days), days - 1)) + " |",
        "|---|" + "---|" * (len(checkpoint_days(days)) + 1),
        *[
            f"| {METHOD_TITLES[m]} | "
            + " | ".join(_fmt(mean_std([score(r.checkpoints[m][d]).accuracy for r in results])) for d in checkpoint_days(days))
            + f" | {_fmt(ms(m, lambda s: s.accuracy))} |"
            for m in METHODS
        ],
        "",
        "![Detection delay by method](dl_delay.png)",
        "",
        *[line for section in X.SECTIONS for line in section(results)],
        "## Confusion matrices (all seeds, test patients)",
        "",
        "Rows: true profile. Columns: predicted profile (and Learning for the rule).",
        "",
        "![Confusion matrices](dl_confusion.png)",
        "",
    ]
    for m in METHODS:
        total = sum(s.confusion for s in scores[m])
        cols = [*PROFILES, *(["learning"] if total[:, -1].any() else [])]
        lines += [f"**{METHOD_TITLES[m]}**", "", "| True \\ predicted | " + " | ".join(cols) + " |",
                  "|---|" + "---|" * len(cols)]
        for i, p in enumerate(PROFILES):
            lines.append(f"| {p} | " + " | ".join(str(int(total[i, j])) for j in range(len(cols))) + " |")
        lines.append("")
    onsets = {p: flag_onset_day(p) for p in ("mci", "moderate")}
    lines += [
        "## Training",
        "",
        "![Training curves](dl_training_curves.png)",
        "",
        "| Model | Best epoch | Best validation loss |",
        "|---|---|---|",
    ]
    for m in METHODS[1:]:
        epochs = mean_std([r.histories[m].best_epoch + 1 for r in results])
        losses = mean_std([min(r.histories[m].val_loss) for r in results])
        lines.append(f"| {METHOD_TITLES[m]} | {_fmt(epochs, 1)} | {_fmt(losses)} |")
    lines += [
        "",
        "## Method",
        "",
        "- **Inputs (sequence models):** one step per session in time order: composite, accuracy (hinted correct "
        "rounds count half), level, log median reaction time, hint rate, log study time, completed, rounds, day, "
        "days since the previous session, missing-value flags and a one-hot game. Standardised with statistics from "
        "the training patients only (reaction and study time per game).",
        "- **Inputs (MLP):** per game, statistics of all sessions up to the day: sessions, mean / first-10 / "
        "last-5 composite, composite slope over time, accuracy, last level, reaction time, hint and completion "
        "rates, study time. Trained on snapshots every 5 days; scored on every day.",
        f"- **Models:** GRU and LSTM with 2 layers of 64 units (dropout 0.2), predicting after every session from "
        "that session and earlier ones only; MLP with 2 hidden layers of 64. Two heads each: profile (3 classes) "
        f"and decline (1). Loss = cross-entropy + binary cross-entropy at every step. Adam (lr {cfg.lr}, weight "
        f"decay {cfg.weight_decay}), batch {cfg.batch_size}, up to {cfg.epochs} epochs, early stopping on the "
        f"validation loss (patience {cfg.patience}).",
        f"- **Early-warning target:** 0 for healthy patients; for mci and moderate patients, 1 from the day their "
        f"simulated ability has dropped by {FLAG_ABILITY_DROP} (day {onsets['mci']} for mci, day "
        f"{onsets['moderate']} for moderate), 0 before. Training on \"declining from day 0\" instead would teach "
        "the models the cohort's 2:1 prior and flag nearly everyone in the first days.",
        "- **Study time** is simulated (the simulator did not have it before): about 1.5 s per card pair or 1.8 s "
        "per word, slower as ability falls, with log-normal noise. It is an assumption, not fitted to real data, "
        "and the rule does not use it, so the GRU is also trained without it.",
        "- **Not in the app:** these models are research code only.",
        "",
        *X.LIMITATIONS,
    ]
    return "\n".join(lines)


def _style(ax) -> None:  # type: ignore[no-untyped-def]
    ax.grid(True, axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=MUTED, labelsize=8)


def plot_confusion(results: Sequence[SeedResult], out: Path) -> None:
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(METHODS), figsize=(3.0 * len(METHODS), 3.3), dpi=200)
    labels = [*PROFILES, "learning"]
    for ax, m in zip(axes, METHODS):
        total = sum(score(r.outcomes[m]).confusion for r in results)
        shown = total if total[:, -1].any() else total[:, :-1]
        rates = shown / shown.sum(axis=1, keepdims=True)
        ax.imshow(rates, cmap="Blues", vmin=0, vmax=1)
        for i in range(shown.shape[0]):
            for j in range(shown.shape[1]):
                ax.text(j, i, f"{int(shown[i, j])}", ha="center", va="center", fontsize=8,
                        color="white" if rates[i, j] > 0.6 else INK)
        ax.set_xticks(range(shown.shape[1]), labels[: shown.shape[1]], fontsize=7, color=MUTED)
        ax.set_yticks(range(3), PROFILES, fontsize=7, color=MUTED)
        ax.set_title(SHORT[m].replace("\n", " "), fontsize=9, color=INK)
        ax.set_xlabel("predicted", fontsize=7, color=MUTED)
        for spine in ax.spines.values():
            spine.set_visible(False)
    axes[0].set_ylabel("true profile", fontsize=7, color=MUTED)
    fig.suptitle("Profile on the last day, test patients over all seeds (shading: share of the row)", fontsize=9,
                 color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out, facecolor="white")
    plt.close(fig)


def plot_delay(results: Sequence[SeedResult], out: Path) -> None:
    """Box plot of the alarm day for detected mci / moderate patients, one box per method; FA rate in the labels."""
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.8), dpi=200, sharey=True)
    for ax, profile in zip(axes, ("mci", "moderate")):
        data, labels, colors = [], [], []
        for m in METHODS:
            outcomes = [o for r in results for o in r.outcomes[m]]
            group = [o for o in outcomes if o.profile == profile]
            days = [o.alarm_day for o in group if o.alarm_day is not None]
            healthy = [o for o in outcomes if o.profile == "healthy"]
            fa = sum(o.alarm_day is not None for o in healthy) / len(healthy)
            data.append(days or [np.nan])
            labels.append(f"{SHORT[m]}\n{len(days) / len(group):.0%} found\n{fa:.0%} false")
            colors.append(RULE if m == "rule_b" else SERIES)
        box = ax.boxplot(data, patch_artist=True, widths=0.55, showfliers=False,
                         medianprops={"color": "white", "linewidth": 1.6},
                         whiskerprops={"color": MUTED}, capprops={"color": MUTED})
        for patch, c in zip(box["boxes"], colors):
            patch.set_facecolor(c)
            patch.set_edgecolor(c)
        ax.set_xticks(range(1, len(METHODS) + 1), labels, fontsize=7, color=MUTED)
        ax.set_title(f"{profile.upper() if profile == 'mci' else 'Moderate'} patients", fontsize=9, color=INK, loc="left")
        _style(ax)
    axes[0].set_ylabel("Day flagged (= detection delay)", fontsize=8, color=MUTED)
    fig.suptitle("Detection delay on test patients, all seeds (lower is earlier; box = IQR, line = median)",
                 fontsize=9, color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out, facecolor="white")
    plt.close(fig)


def plot_training(results: Sequence[SeedResult], out: Path) -> None:
    import matplotlib.pyplot as plt

    models = METHODS[1:]
    fig, axes = plt.subplots(1, len(models), figsize=(3.0 * len(models), 3.0), dpi=200, sharey=True)
    for ax, m in zip(axes, models):
        for r in results:
            h = r.histories[m]
            x = range(1, len(h.train_loss) + 1)
            ax.plot(x, h.train_loss, color=SERIES, alpha=0.35, linewidth=1.0)
            ax.plot(x, h.val_loss, color=SERIES, alpha=0.9, linewidth=1.2, linestyle="--")
            ax.plot(h.best_epoch + 1, h.val_loss[h.best_epoch], "o", color=SERIES, markersize=3)
        ax.set_title(SHORT[m].replace("\n", " "), fontsize=9, color=INK, loc="left")
        ax.set_xlabel("epoch", fontsize=7, color=MUTED)
        _style(ax)
    axes[0].set_ylabel("loss (CE + BCE)", fontsize=8, color=MUTED)
    fig.suptitle("Training curves, one line per seed: solid = train, dashed = validation, dot = kept epoch",
                 fontsize=9, color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(out, facecolor="white")
    plt.close(fig)


def write_report(results: Sequence[SeedResult], per_profile: int, days: int, cfg: TrainConfig, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    out.mkdir(parents=True, exist_ok=True)
    (out / "dl_decline.md").write_text(to_markdown(results, per_profile, days, cfg) + "\n", encoding="utf-8")
    with (out / "dl_decline.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["method", "seed", "metric", "group", "value"])
        writer.writeheader()
        writer.writerows(to_rows(results))
        writer.writerows(X.extra_rows(results))
    X.write_sweep_csv(results, out / "dl_sweep.csv")
    X.plot_tradeoff(results, out / "dl_tradeoff.png")
    plot_confusion(results, out / "dl_confusion.png")
    plot_delay(results, out / "dl_delay.png")
    plot_training(results, out / "dl_training_curves.png")
