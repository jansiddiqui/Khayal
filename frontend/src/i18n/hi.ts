/** "11 बजकर 10 मिनट", "साढ़े 3 बजे", "सवा 4 बजे", "पौने 5 बजे", "डेढ़ बजे", "ढाई बजे", "12 बजने में 20 मिनट". */
function clockTime(h: number, m: number, asWords = false): string {
  const n = (x: number) => (asWords ? NUMBER_WORDS[x]! : String(x));
  const next = h === 12 ? 1 : h + 1;
  if (m === 0) return `${n(h)} बजे`;
  if (m === 30) return h === 1 ? "डेढ़ बजे" : h === 2 ? "ढाई बजे" : `साढ़े ${n(h)} बजे`;
  if (m === 15) return `सवा ${n(h)} बजे`;
  if (m === 45) return `पौने ${n(next)} बजे`;
  return m < 30 ? `${n(h)} बजकर ${n(m)} मिनट` : `${n(next)} बजने में ${n(60 - m)} मिनट`;
}

