/** "11 بج کر 10 منٹ", "ساڑھے 3 بجے", "سوا 4 بجے", "پونے 5 بجے", "ڈیڑھ بجے", "ڈھائی بجے", "12 بجنے میں 20 منٹ". */
function clockTime(h: number, m: number, asWords = false): string {
  const n = (x: number) => (asWords ? NUMBER_WORDS[x]! : String(x));
  const next = h === 12 ? 1 : h + 1;
  if (m === 0) return `${n(h)} بجے`;
  if (m === 30) return h === 1 ? "ڈیڑھ بجے" : h === 2 ? "ڈھائی بجے" : `ساڑھے ${n(h)} بجے`;
  if (m === 15) return `سوا ${n(h)} بجے`;
  if (m === 45) return `پونے ${n(next)} بجے`;
  return m < 30 ? `${n(h)} بج کر ${n(m)} منٹ` : `${n(next)} بجنے میں ${n(60 - m)} منٹ`;
}

